function load(file, modules, globals = {}) {
  const source = ts.transpileModule(fs.readFileSync(base + file, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const context = { exports: {}, require: (id) => id === 'react/jsx-runtime' ? jsx : id === '../visualStyles' ? load('visualStyles.ts', {}) : modules[id],
    setTimeout, clearTimeout, setInterval, clearInterval, URL, FormData, File, console, ...globals };
  vm.runInNewContext(source, context, { filename: file });
  return context.exports;
}

function harness() {
  const values = [];
  const effects = [];
  let index = 0;
  const react = {
    useState(init) {
      const slot = index++;
      if (!(slot in values)) values[slot] = typeof init === 'function' ? init() : init;
      return [values[slot], (next) => { values[slot] = typeof next === 'function' ? next(values[slot]) : next; }];
    },
    useRef(value) { const slot = index++; return values[slot] ?? (values[slot] = { current: value }); },
    useEffect(fn) { effects.push(fn); },
    useMemo(fn) { return fn(); },
    useCallback(fn) { return fn; },
    lazy() { return PreviewMarker; },
    Suspense: () => null,
  };
  return { react, effects, render: (Component, props) => { index = 0; effects.length = 0; return Component(props); } };
}

function find(tree, predicate) {
  if (Array.isArray(tree)) { for (const child of tree) { const result = find(child, predicate); if (result) return result; } }
  else if (tree && typeof tree === 'object') {
    if (predicate(tree)) return tree;
    return find(tree.props?.children, predicate);
  }
}
